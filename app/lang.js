const RX = [
  [/^Raum ist voll \((\d+) Spieler\)$/, 'Room is full ($1 players)'],
  [/^Höchstens (\d+) Bots je Raum$/, 'At most $1 bots per room'],
  [/^Veralteter Spielstand \(Hand (\d+) < (\d+)\)$/, 'Outdated game state (hand $1 < $2)'],
  [/^Für Online-Räume ist eine neuere Spiellogik nötig \(Version (\d+)\)\..*$/,
    'Online rooms need newer game logic (version $1). Please load the update – in the app at startup, in the browser by reloading. Old app versions: please update in the App Store or Google Play, or install the new APK.'],
];
function en(msg) {
  if (typeof msg !== 'string') return msg;
  if (Object.prototype.hasOwnProperty.call(EN, msg)) return EN[msg];
  for (const [r, t] of RX) if (r.test(msg)) return msg.replace(r, t);
  return msg;
}
function wantsEn(req) { return !!(req && req.headers && /^en/i.test(String(req.headers['x-kr-lang'] || ''))); }
module.exports = { en, wantsEn, EN };
